/// Small PDF fixtures for the PDF flow, embedded as base64 because files
/// under `integration_test/` are not shipped to the device.
///
/// Regenerate (Python reportlab + qpdf):
/// - `plain`: 3 A4 pages, one text line and a rectangle each
///   (`reportlab.pdfgen.canvas`, `pageCompression=1`).
/// - `locked`: `qpdf --encrypt e2e-user e2e-owner 256 -- plain.pdf locked.pdf`
///   (needs a user password to open).
/// - `corrupt`: the first 400 bytes of `plain.pdf` (header, no xref/trailer).
enum PdfFixture {
  plain('e2e_plain.pdf', 3),
  locked('e2e_locked.pdf', 3),
  corrupt('e2e_corrupt.pdf', 0);

  const PdfFixture(this.fileName, this.pageCount);

  /// File name the fixture is written under (the import uses it as title).
  final String fileName;

  /// Pages in the fixture (0 when it cannot be opened).
  final int pageCount;

  Uint8List get bytes => base64Decode(switch (this) {
        PdfFixture.plain => _plain,
        PdfFixture.locked => _locked,
        PdfFixture.corrupt => _corrupt,
      });

  /// Writes the fixture to a fresh file in the temp directory, the way a
  /// file picker hands over a cached copy.
  Future<File> writeToTemp() async {
    final dir = await getTemporaryDirectory();
    final file = File(p.join(dir.path, 'e2e_fixtures', fileName));
    await file.parent.create(recursive: true);
    return file.writeAsBytes(bytes, flush: true);
  }
}

